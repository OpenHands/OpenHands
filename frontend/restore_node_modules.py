"""
Restore missing package.json files in node_modules by fetching from npm registry.
Uses package-lock.json to find exact versions.
"""
import json
import os
import urllib.request
import urllib.error
import sys

LOCK_PATH = "package-lock.json"
NODE_MODULES = "node_modules"
REGISTRY = "https://registry.npmjs.org"

def load_lockfile():
    with open(LOCK_PATH) as f:
        return json.load(f)

def find_packages_missing_package_json():
    missing = []
    # Get all first-level and scoped packages
    for entry in os.scandir(NODE_MODULES):
        if entry.name.startswith('.'):
            continue
        if entry.is_dir():
            if entry.name.startswith('@'):
                # Scoped package - check subdirs
                for sub in os.scandir(entry.path):
                    if sub.is_dir():
                        pj = os.path.join(sub.path, "package.json")
                        if not os.path.exists(pj):
                            pkg_name = f"{entry.name}/{sub.name}"
                            missing.append((pkg_name, sub.path))
            else:
                pj = os.path.join(entry.path, "package.json")
                if not os.path.exists(pj):
                    missing.append((entry.name, entry.path))
    return missing

def get_version_from_lock(lock, pkg_name):
    key = f"node_modules/{pkg_name}"
    if key in lock.get("packages", {}):
        return lock["packages"][key].get("version")
    return None

def fetch_and_restore_package_json(pkg_name, pkg_path, version):
    pkg_encoded = pkg_name.replace("/", "%2F")
    url = f"{REGISTRY}/{pkg_encoded}/{version}"
    try:
        req = urllib.request.Request(url, headers={"Accept": "application/json"})
        with urllib.request.urlopen(req, timeout=30) as resp:
            data = json.loads(resp.read())
        # Write the package.json
        pj_path = os.path.join(pkg_path, "package.json")
        with open(pj_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        return True
    except Exception as e:
        print(f"  ERROR: {e}")
        return False

def main():
    print("Loading package-lock.json...")
    lock = load_lockfile()
    
    print("Scanning for missing package.json files...")
    missing = find_packages_missing_package_json()
    print(f"Found {len(missing)} packages missing package.json")
    
    restored = 0
    failed = []
    
    for pkg_name, pkg_path in missing:
        version = get_version_from_lock(lock, pkg_name)
        if not version:
            print(f"  SKIP (no version in lockfile): {pkg_name}")
            continue
        
        print(f"  Restoring {pkg_name}@{version}...", end=" ")
        sys.stdout.flush()
        success = fetch_and_restore_package_json(pkg_name, pkg_path, version)
        if success:
            print("OK")
            restored += 1
        else:
            print("FAILED")
            failed.append(pkg_name)
    
    print(f"\nRestored: {restored}/{len(missing)}")
    if failed:
        print(f"Failed: {failed}")

if __name__ == "__main__":
    main()
